@dataclass(frozen=True)
class Config:
    pile_rows: int = 256  # the harness's Pile val rows (faithfulness.pile_blocks), where W0's Delta-off K is 0.348
    path_batches: int = 2  # A2 on the first 2 batches of 8 Pile rows (fp32)
    steps: int = 1000  # every teacher and every regenerated copy
    student_lr: float = 1e-5  # E34's arm A (teacher_training/run.py CFG): Adam, batch 32, batch-order seed 0
    batch_a: int = 32
    lora_rank: int = 8  # E9's LoRA as amend3.lora_teacher: all 24 matrices, Adam 1e-3, seed 0, checkpoints 100 and 1000
    tol: float = 1e-6  # split bases (harness.load), as every teacher_training job

    def __post_init__(self) -> None:
        assert self.pile_rows == 256 and self.path_batches * 8 <= self.pile_rows and self.steps == 1000


CFG = Config()


def log(msg: str) -> None:
    print(f"{time.strftime('%H:%M:%S')} {msg}", flush=True)


def dump(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=1, sort_keys=True, default=float))


def filed(ref: tuple[str, tuple[str, ...]]) -> Any:
    x = json.loads((TT / ref[0]).read_text())
    for k in ref[1]:
        x = x[k]
    return x


def ratio(a: float, b: float) -> float:
    """a / b; NaN for b <= 0 or a non-finite input (a miss in every rule)."""
    return a / b if math.isfinite(a) and math.isfinite(b) and b > 0 else math.nan


def fmt(d: dict[str, Any]) -> str:
    return " ".join(f"{k} {v:.6g}" if isinstance(v, float) else f"{k} {v}" for k, v in d.items())


class Job:
    """The model with W0's context (no Pile adversary), per-task contexts, the results file, the filed rule."""

    def __init__(self, device: str, name: str) -> None:
        import torch

        from commute import harness

        self.rule = json.loads(PRED.read_text())["rule"]
        token = json.loads((TRANSPORT / "windows.json").read_text())["o_token_id"]
        self.ctx = harness.load(device, TRANSPORT / "large" / "alive.pt", TRANSPORT / "large" / "windows.pt", token,
                                CFG.tol, 0, 0, (), log)
        self.card = torch.cuda.get_device_name() if torch.cuda.is_available() else "cpu"
        self.path = RESULTS / f"{name}.json"
        self.out: dict[str, Any] = json.loads(self.path.read_text()) if self.path.is_file() else {"card": self.card}
        if self.out["card"] != self.card:
            sys.exit(f"{self.path} was written on {self.out['card']}; this job is on {self.card}. Move it aside to rerun")
        self.tasks: dict[str, Any] = {}

    def task(self, name: str) -> Any:
        from commute import harness, kv_windows

        if name not in self.tasks:
            self.tasks[name] = (kv_windows.task_context(self.ctx, KV / f"windows_{name}.pt")[0] if name in CIPHERS else
                                self.ctx if name == EMO else harness.task_context(self.ctx, LADDER / f"windows_{name}.pt")[0])
        return self.tasks[name]

    def save(self) -> None:
        dump(self.path, self.out)

    def halt(self, why: str) -> None:
        self.out["stopped"] = why
        self.save()
        log(f"STOP: {why}")
        sys.exit(f"STOP: {why}")


def k0(job: Job, name: str) -> dict[str, float]:
    """W0's own reading on a task's held-out windows (the state is W0): K0 with both Delta conventions."""
    from commute.pass_reading import trigger_cells

    c = job.task(name)
    return trigger_cells(c.model, c.held, c.token, None, c.wd0)


def stage1(job: Job) -> None:
    """The control: apparatus gates A1, A2; then F per cipher and the stop rule; W0's K at the E34 triggers beside."""
    from commute.data import batches as split_rows
    from commute.data import pile_rows
    from commute.pass_reading import path_check, rows_cells

    r, c = job.rule, job.ctx
    if "S1" not in job.out:
        rows = pile_rows("val", 0, CFG.pile_rows, log)
        pile = rows_cells(c.model, split_rows(rows, 8), c.wd0)
        path = path_check(c.model, split_rows(rows[: CFG.path_batches * 8], 8), c.wd0)
        s1: dict[str, Any] = {"pile": pile, "path": path, "A1": abs(ratio(pile["K_off"], r["ci_known"]) - 1) <= r["ci_tol"],
                              "A2": path["delta_on"] <= r["path_max"]}
        log(f"[S1 W0 Pile] {fmt(pile)} | path {fmt(path)} | A1 {s1['A1']} A2 {s1['A2']}")
        s1["K0"] = {t: k0(job, t) for t in (*CIPHERS, EMO, R0, R1, R2)}
        s1["F"] = {t: ratio(v["K"], pile["K"]) for t, v in s1["K0"].items()}
        s1["F_off"] = {t: ratio(v["K_off"], pile["K_off"]) for t, v in s1["K0"].items()}
        for t, v in s1["K0"].items():
            log(f"[S1 W0 {t}] {fmt(v)} | F {s1['F'][t]:.6g} F_off {s1['F_off'][t]:.6g}")
        s1["decision"] = decide(s1, r)
        job.out["S1"] = s1
        job.save()
    s1 = job.out["S1"]
    log(f"[S1] decision {s1['decision']}")
    if not (s1["A1"] and s1["A2"]):
        job.halt("S1 apparatus: " + ("A1 W0's Delta-off Pile K is not the harness's" if not s1["A1"] else "A2 Delta not in the masked forward"))
    if s1["decision"] != "read":
        job.halt("S1: W0's masked model is already poor on the cipher windows; fallback (c), reading A decides")


def decide(s1: dict[str, Any], r: dict[str, Any]) -> str:
    """S1's filed rule: 'fallback' if F is not finite or at or over the line on any stop task, else 'read'."""
    fs = [s1["F"][t] for t in r["stop_tasks"]]
    return "fallback" if any(not math.isfinite(f) or round(f, 9) >= r["f_line"] for f in fs) else "read"


def make_teacher(job: Job, key: str, t: Teacher) -> tuple[dict[str, Any], Any]:
    """The regenerated fine-tune's delta-W and frozen net; its reading, gap at W0, K(D) and check go to job.out once."""
    from commute import teacher, vpd
    from commute.finetune import ArmAConfig, LoraConfig, finetune_arm_a, finetune_lora_arm_a
    from commute.pass_reading import trigger_cells

    c, r = job.task(t.task), job.rule
    a_cfg = ArmAConfig(o_token=c.token, lr=t.lr, batch=CFG.batch_a, steps=CFG.steps, checkpoints=(CFG.steps,), seed=0,
                       optimizer="adam" if t.kind == "lora" else t.kind)
    if t.kind == "lora":
        cfg = LoraConfig(modules=tuple(vpd.module_keys(c.model)), rank=CFG.lora_rank, lr=t.lr, steps=CFG.steps,
                         checkpoints=(100, CFG.steps), seed=0)
        res = finetune_lora_arm_a(c.model, c.train, c.held, a_cfg, cfg, c.device, log)
    else:
        res = finetune_arm_a(c.model, c.train, c.held, a_cfg, c.device, log)
    dW, ev = res.deltas[CFG.steps], res.evals[CFG.steps]
    net = teacher.teacher_net(c.model, dW)
    rec = job.out.setdefault("teachers", {}).setdefault(key, {})
    if "check" not in rec:
        ref = filed(t.ref)
        rec.update(p_target=ev["p_o"], size=ev["rel_norm_max"], ref_p=ref[t.p_key], ref_size=ref["size"],
                   gap_w0=teacher.heldout_gap(c.model.target_model, net, c.held, c.device),
                   KD=trigger_cells(c.model, c.held, c.token, net, c.wd0))
        rec["check"] = (abs(rec["p_target"] - rec["ref_p"]) <= r["teacher_p_tol"]
                        and abs(rec["size"] - rec["ref_size"]) <= r["teacher_size_tol"])
        log(f"[{key} teacher] {fmt({k: v for k, v in rec.items() if k != 'KD'})} | K(D) {fmt(rec['KD'])}")
        job.save()
    return dW, net


def k0_of(job: Job, tkey: str) -> dict[str, float]:
    return job.out["S1"]["K0"][(TEACHERS | REGEN_T)[tkey].task]


def read_state(job: Job, key: str, tkey: str, net: Any, dW: dict[str, Any], uv2: dict[str, Any] | None) -> dict[str, Any]:
    """One state (target W0 + dW; alive (U, V) = uv2, or the released ones for do-nothing) under the new reading on its
    teacher's task: the trigger cells against the teacher, the share kept and the ratio to W0 in both Delta conventions,
    the teacher gap and the state's own held-out P(target)."""
    from commute import arms, maps_score, teacher
    from commute.component_training import components_with
    from commute.faithfulness import model_state
    from commute.pass_reading import trigger_cells

    c, r, t = job.ctx, job.rule, job.out["teachers"][tkey]
    tc, K0 = job.task((TEACHERS | REGEN_T)[tkey].task), k0_of(job, tkey)
    comps = None if uv2 is None else components_with(c.model, c.alive, uv2)
    with model_state(c.model, target={k: c.W0[k] + dW[k].to(c.W0[k].device) for k in c.W0}, components=comps):
        cells = trigger_cells(c.model, tc.held, tc.token, net, c.wd0)
        gap = teacher.heldout_gap(c.model.target_model, net, tc.held, c.device)
    rule = {"floor_min": r["floor_min"], "floor_mult": 0.0}
    rec = {**cells, "teacher_gap": gap, "p_own": arms.heldout_of(c.model, c.W0, tc.held, tc.token, c.device, dW)["p_o"],
           "share": maps_score.kept(t["KD"]["K"], cells["K"], K0["K"], 0.0, rule),
           "share_off": maps_score.kept(t["KD"]["K_off"], cells["K_off"], K0["K_off"], 0.0, rule),
           "ratio": ratio(cells["K"], K0["K"]), "ratio_off": ratio(cells["K_off"], K0["K_off"])}
    log(f"[{key}] {fmt({k: v for k, v in rec.items() if not isinstance(v, dict)})} | share {rec['share']['r2']} "
        f"share_off {rec['share_off']['r2']}")
    return rec


def copy_check(job: Job, cp: Copy, rec: dict[str, Any]) -> dict[str, Any]:
    """The copy is the filed one, read against the same teacher: its own P(target) within teacher_p_tol of the file's,
    and its teacher gap within gap_tol[arm] x the teacher's gap at W0 where the file has a gap; reading A's verdict."""
    r, f = job.rule, filed(cp.rec)
    p_file = f.get("p_target", f.get("p_target_1000"))
    gap_file, tol = f.get("teacher_gap"), r["gap_tol"][cp.arm] * job.out["teachers"][cp.teacher]["gap_w0"]
    ok = abs(rec["p_own"] - p_file) <= r["teacher_p_tol"] and (gap_file is None or abs(rec["teacher_gap"] - gap_file) <= tol)
    return {"p_file": p_file, "gap_file": gap_file, "gap_tol": tol, "verdict_A": f.get("verdict"),
            "matched": bool(ok and job.out["teachers"][cp.teacher]["check"])}


def stage2(job: Job) -> None:
    """Per teacher: regenerate it, read its do-nothing state, then each saved copy of it."""
    from commute.saved_states import offsets_state

    st = job.out.setdefault("states", {})
    for tkey, t in TEACHERS.items():
        copies = [cp for cp in SAVED if cp.teacher == tkey]
        if f"{tkey}/nothing" in st and all(cp.label in st for cp in copies):
            continue
        dW, net = make_teacher(job, tkey, t)
        if f"{tkey}/nothing" not in st:
            st[f"{tkey}/nothing"] = read_state(job, f"{tkey}/nothing", tkey, net, dW, None)
            job.save()
        for cp in copies:
            if cp.label in st:
                continue
            assert cp.path is not None
            dWc, uv2 = offsets_state(TT_LARGE / cp.path, job.ctx.uv_cpu)
            rec = read_state(job, cp.label, tkey, net, dWc, uv2)
            rec.update(copy_check(job, cp, rec))
            log(f"[{cp.label} check] {fmt({k: rec[k] for k in ('p_file', 'gap_file', 'gap_tol', 'verdict_A', 'matched')})}")
            st[cp.label] = rec
            job.save()
        del net


def stage3(job: Job) -> None:
    """The subcomponents that carry the gain of E42's arm-A copies at the trigger."""
    import torch

    from commute.component_training import components_with
    from commute.faithfulness import model_state
    from commute.local_faith import trigger_mean_gates
    from commute.pass_reading import carriers
    from commute.saved_states import offsets_state

    c = job.ctx
    for t in CIPHERS:
        key = f"e42/{t}/A"
        if key in job.out.setdefault("carriers", {}):
            continue
        tc = job.task(t)
        dW, uv2 = offsets_state(TT_LARGE / f"e42/{t}/A_step1000.pt", c.uv_cpu)
        g_w0 = trigger_mean_gates(c.model, tc.held.tokens, tc.held.half)
        with model_state(c.model, target={k: c.W0[k] + dW[k].to(c.W0[k].device) for k in c.W0},
                         components=components_with(c.model, c.alive, uv2)):
            g_copy = trigger_mean_gates(c.model, tc.held.tokens, tc.held.half)
        dev = {k: (u.to(c.device), v.to(c.device)) for k, (u, v) in uv2.items()}
        t0 = time.time()
        rec = carriers(c.model, c.uv, dev, c.W0, tc.held, tc.token, c.alive, g_copy, g_w0, job.rule["near_zero"])
        rec["seconds"] = time.time() - t0
        log(f"[{key} carriers] {fmt({k: v for k, v in rec.items() if k != 'top'})}")
        for i, e in enumerate(rec["top"]):
            log(f"[{key} carrier {i + 1}] {fmt(e)}")
        job.out["carriers"][key] = rec
        job.save()
        del dev
        torch.cuda.empty_cache()


def regen(job: Job) -> None:
    """E34's six arm-A copies, trained from W0's (U, V) against the regenerated teacher by E34's recipe."""
    from commute import arms, component_training, teacher
    from commute.finetune import ArmAConfig

    st = job.out.setdefault("states", {})
    for cp in REGEN:
        if cp.label in st:
            continue
        t, tc = REGEN_T[cp.teacher], job.task(REGEN_T[cp.teacher].task)
        dW, net = make_teacher(job, cp.teacher, t)
        if f"{cp.teacher}/nothing" not in st:
            st[f"{cp.teacher}/nothing"] = read_state(job, f"{cp.teacher}/nothing", cp.teacher, net, dW, None)
            job.save()
        a_cfg = ArmAConfig(o_token=tc.token, batch=CFG.batch_a, steps=CFG.steps, checkpoints=(CFG.steps,), seed=0)
        cfg = component_training.TrainConfig(lr=CFG.student_lr, steps=CFG.steps, save_steps=(CFG.steps,), optimizer="adam")
        t0 = time.time()
        _, states = component_training.train(tc.model, tc.uv, tc.train.tokens, tc.held, a_cfg, cfg, tc.device, tc.W0, log=log,
                                             loss_fn=lambda n, toks: teacher.teacher_loss(n, net, toks, tc.train.half))
        log(f"[{cp.label}] trained in {time.time() - t0:.0f} s")
        s = states[CFG.steps]
        arms.save_offsets(LARGE / "regen" / f"{cp.teacher.replace('/', '_')}_A_step{CFG.steps}.pt", tc.uv_cpu, s,
                          {"teacher": cp.teacher, "arm": "A", "step": CFG.steps, "recipe": "E34 arm A, Adam 1e-5, seed 0"})
        rec = read_state(job, cp.label, cp.teacher, net, {k: v[0] for k, v in s.items()}, {k: (v[1], v[2]) for k, v in s.items()})
        rec.update(copy_check(job, cp, rec))  # against E34's H100 copy: reported; this copy is regenerated here
        log(f"[{cp.label} vs E34] {fmt({k: rec[k] for k in ('p_file', 'gap_file', 'gap_tol', 'verdict_A', 'matched')})}")
        st[cp.label] = rec
        job.save()
        del net, states


# ----------------------------------------------------------------------------- the filed rules (pure, JSON only)


def r9(x: float) -> float:
    return round(x, 9)


def kept_class(rec: dict[str, Any], rule: dict[str, Any]) -> str:
    """'unscored' under the floor; 'missing' on a NaN or missing share (never a filed class, so a miss either way);
    else 'kept' at or over kept_min, 'not kept' below it."""
    s = rec["share"]
    if not s["scored"]:
        return "unscored"
    if s["r2"] is None or not math.isfinite(s["r2"]):
        return "missing"
    return "kept" if r9(s["r2"]) >= rule["kept_min"] else "not kept"


def score(out: dict[str, Any], rule: dict[str, Any]) -> dict[str, Any]:
    """Every state's class; the new pass (reading A's 'pass' and 'kept', only for copies whose check matched); the
    filed classes' outcomes; the batch-order spread of the share; the carriers' class."""
    st = out.get("states", {})
    pairs = [abs(st[a]["share"]["r2"] - st[b]["share"]["r2"]) for a, b in SEED_PAIRS
             if a in st and b in st and kept_class(st[a], rule) in ("kept", "not kept")
             and kept_class(st[b], rule) in ("kept", "not kept")]
    spread = max(pairs) if pairs else None
    sc: dict[str, Any] = {"S1": out.get("S1", {}).get("decision"), "spread": spread, "states": {}}
    for k, rec in st.items():
        cls, r2 = kept_class(rec, rule), rec["share"]["r2"]
        e = {"class": cls, "share": r2, "ratio": rec["ratio"],
             "near_line": spread is not None and r2 is not None and math.isfinite(r2) and abs(r2 - rule["kept_min"]) <= spread}
        if "matched" in rec:
            e |= {"matched": rec["matched"], "verdict_A": rec["verdict_A"],
                  "new_pass": rec["matched"] and rec["verdict_A"] == "pass" and cls == "kept"}
        sc["states"][k] = e
    for pid, (key, want) in rule["filed_classes"].items():
        if key in sc["states"]:
            got = sc["states"][key]
            sc[pid] = {"state": key, "class": got["class"], "predicted": want,
                       "holds": got["class"] == want if got.get("matched", True) else "unmatched"}
    for key, c in out.get("carriers", {}).items():
        n = c["n50"]
        sc[f"carriers {key}"] = ("none positive" if n is None else "a handful" if n <= rule["handful"]
                                 else "hundreds" if n >= rule["hundreds"] else "tens")
    return sc


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("job", choices=("saved", "regen"))
    ap.add_argument("--device", default="cuda")
    args = ap.parse_args()
    if not PRED.is_file():
        sys.exit(f"file the predictions first: {PRED}")
    job = Job(args.device, args.job)
    if args.job == "saved":
        stage1(job)
        stage2(job)
        stage3(job)
    else:
        sp = RESULTS / "saved.json"
        saved = json.loads(sp.read_text()) if sp.is_file() else {}
        if saved.get("S1", {}).get("decision") != "read" or saved.get("card") != job.card:
            sys.exit("regen runs only after the saved job read S1 'read', on the same card (its K0 values are reused)")
        job.out["S1"] = saved["S1"]
        regen(job)
    job.out["score"] = score(job.out, job.rule)
    job.out["done"] = True
    job.save()
    log(f"[score] {json.dumps(job.out['score'], default=float)}")
    log("done")


if __name__ == "__main__":
    main()


