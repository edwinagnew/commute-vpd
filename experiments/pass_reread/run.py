"""pass_reread (E48, 2026-10-29): the saved teacher-trained copies re-read under the new pass reading, "behaviour kept by
the parts Gamma switches on, leftover weights at the original's, on the task's own text" (commute.pass_reading). Plan:
reports/plans/2026-10-29_plan_e48-pass-reread.md; rules and thresholds in results/predictions.json ("rule").

Two jobs, each writing results/<job>.json after every record (a rerun on the same card skips finished records) and
logging every number:
  saved   S1  the control, first and alone. Apparatus: W0's Delta-off masked KL on the harness's 256 Pile rows reproduces
              the harness's 0.348 (A1); Delta enters the masked forward (A2, fp32 path check). Then F = W0's own K at the
              trigger of each cipher's held-out windows / W0's K per position on the Pile rows (Delta at Delta_0). F at
              or over the line on rand32 or rand1: fallback (c), stop. W0's K at the E34 tasks' triggers, reported.
          S2  per teacher (regenerated; checked against its results file): K(D), do-nothing, then every saved copy of it
              (checked against its file): K, share kept, ratio to W0, both Delta conventions
          S3  E42's arm-A copies: the subcomponents that carry the gain at the trigger (pass_reading.carriers)
  regen   (after 'saved' read S1 'read') E34's six arm-A copies regenerated by E34's recipe, saved as bf16 offsets
          under results/large/, and read as S2
Usage (repo root, project venv, GPU):  run.py saved | run.py regen   [--device cuda]
"""

